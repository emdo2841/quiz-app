let questions = [];
let currentQuestion = 0;
let score = 0;
let timer;
let timeLeft = 10;
let playerName = "";

const questionEl = document.getElementById("question");
const answersEl = document.getElementById("answers");
const nextBtn = document.getElementById("next-btn");
const timerEl = document.getElementById("timer");
const progressBar = document.getElementById("progress-bar");

function shuffle(array) {
  return array.sort(() => Math.random() - 0.5);
}

function startGame() {
  const nameInput = document.getElementById("player-name").value.trim();
  const category = document.getElementById("category").value;
  if (!nameInput) return alert("Please enter your name");
  if (!quizData[category]) return alert("Invalid category");

  playerName = nameInput;
  questions = shuffle([...quizData[category]]).slice(0, 10);
  score = 0;
  currentQuestion = 0;

  document.getElementById("start-screen").style.display = "none";
  document.getElementById("quiz-container").style.display = "block";
  showQuestion(currentQuestion);
}

function startTimer() {
  clearInterval(timer);
  timeLeft = 10;
  timerEl.textContent = `Time left: ${timeLeft}s`;
  timer = setInterval(() => {
    timeLeft--;
    timerEl.textContent = `Time left: ${timeLeft}s`;
    if (timeLeft <= 0) {
      clearInterval(timer);
      selectAnswer(-1);
    }
  }, 1000);
}

function showQuestion(index) {
  const q = questions[index];
  questionEl.textContent = q.question;
  answersEl.innerHTML = "";
  q.answers.forEach((answer, i) => {
    const btn = document.createElement("button");
    btn.textContent = answer;
    btn.className = "answer-btn";
    btn.onclick = () => selectAnswer(i);
    answersEl.appendChild(btn);
  });
  updateProgress();
  nextBtn.disabled = true;
  startTimer();
}

function selectAnswer(index) {
  clearInterval(timer);
  const correctIndex = questions[currentQuestion].correct;
  const buttons = answersEl.querySelectorAll("button");

  buttons.forEach((btn, i) => {
    btn.disabled = true;
    if (i === correctIndex) btn.style.backgroundColor = "green";
    if (i === index && i !== correctIndex) btn.style.backgroundColor = "red";
  });

  if (index === correctIndex) score++;
  nextBtn.disabled = false;
}

nextBtn.onclick = () => {
  currentQuestion++;
  if (currentQuestion < questions.length) {
    showQuestion(currentQuestion);
  } else {
    showScore();
  }
};

function updateProgress() {
  const percent = (currentQuestion / questions.length) * 100;
  progressBar.style.width = `${percent}%`;
}

function showScore() {
  let scoreHistory = JSON.parse(localStorage.getItem("scoreHistory")) || [];
  scoreHistory.unshift({ name: playerName, score });
  scoreHistory = scoreHistory.slice(0, 5);
  localStorage.setItem("scoreHistory", JSON.stringify(scoreHistory));

  document.getElementById("quiz-container").innerHTML = `
        <h2>Quiz Finished</h2>
        <p>${playerName}, your score: ${score} / ${questions.length}</p>
        <h3>Last 5 Scores:</h3>
        <ul>
          ${scoreHistory
            .map((s, i) => `<li>${s.name}: ${s.score}/${questions.length}</li>`)
            .join("")}
        </ul>
        <button onclick="location.reload()">Restart Quiz</button>
      `;
}
